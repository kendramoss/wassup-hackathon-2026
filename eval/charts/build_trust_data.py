# Builds the data behind the trust documents from committed files only:
# the "Known failure cases" section of the Accuracy page (docs/MODEL-CARD.md)
# and the corpus counts in docs/DATASHEET.md. No model calls, no network,
# standard library only. Deterministic.
#
# Every held-out miss is listed, not a selection: the page shows the
# auto-accepted ones first and the rest behind a toggle.
#
# Usage (from the repo root):
#   python3 -I eval/charts/build_trust_data.py .          # write the outputs
#   python3 -I eval/charts/build_trust_data.py . --check  # fail if they are stale
#
# Reads:  eval/results/final-gemini-4-argon-prec-engine-v1-vertex.jsonl (the official held-out run)
#         eval/results/scope-final-router-v2-vertex.jsonl (router scope, for the fast path)
#         eval/data/labels.jsonl (ruling subject, collection, label method)
#         eval/splits/splits_final.json (split membership, for the datasheet)
#         backend/data/facts/ (the bundled facts pool, counted only)
#         backend/internal/calibrate/map.json (the calibration map the product applies, D160)
# Writes: frontend/src/lib/failure-cases.json
#         eval/results/corpus-stats.json

import hashlib
import json
import math
import os
import sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "."
CHECK = "--check" in sys.argv[2:]

RUN = "eval/results/final-gemini-4-argon-prec-engine-v1-vertex.jsonl"
SCOPE = "eval/results/scope-final-router-v2-vertex.jsonl"
LABELS = "eval/data/labels.jsonl"
OUT = "frontend/src/lib/failure-cases.json"
STATS = "eval/results/corpus-stats.json"
SPLITS = "eval/splits/splits_final.json"
FACTS = "backend/data/facts"
BAR = 0.92
CAL_MAP = "backend/internal/calibrate/map.json"
MIN_N = 19  # origins with at least this many held-out rulings get their own row


def path(p):
    return f"{ROOT}/{p}"


def jsonl(p):
    with open(path(p)) as f:
        return [json.loads(line) for line in f if line.strip()]


def sha256(p):
    with open(path(p), "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def wilson(k, n):
    z = 1.96
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return round(c - h, 4), round(c + h, 4)


def calibrated(m, stated):
    # The same rule as calibrate.Map.Value: the step at or below the value,
    # or the lowest step for a value under every step.
    v = m["steps"][0]["calibrated"]
    for st in m["steps"]:
        if stated >= st["from"]:
            v = st["calibrated"]
    return v


def rate(label, rows):
    k = sum(r["correct"] for r in rows)
    lo, hi = wilson(k, len(rows))
    return {"origin": label, "n": len(rows), "correct": k, "ci_low": lo, "ci_high": hi}


def build():
    rows = jsonl(RUN)
    scope = {r["ruling"]: r for r in jsonl(SCOPE)}
    labels = {r["ruling"]: r for r in jsonl(LABELS)}
    with open(path(CAL_MAP)) as f:
        cal = json.load(f)

    def auto(r):
        return r["confidence"] >= BAR and scope[r["ruling"]]["in_scope"]

    misses = []
    for r in sorted((r for r in rows if not r["correct"]), key=lambda r: (not auto(r), r["date"], r["ruling"])):
        lab = labels[r["ruling"]]
        misses.append(
            {
                "ruling": r["ruling"],
                "date": r["date"],
                "subject": lab["subject"].strip(),
                "collection": lab["collection"],
                "label_method": r["label_method"],
                "cbp_held": r["gold"],
                "predicted": r["pred"],
                "confidence": r["confidence"],
                "calibrated": calibrated(cal, r["confidence"]),
                "auto_accepted": auto(r),
            }
        )

    counts = {}
    for r in rows:
        counts[r["gold"]] = counts.get(r["gold"], 0) + 1
    big = sorted((c for c, n in counts.items() if n >= MIN_N), key=lambda c: (-counts[c], c))
    by_origin = [rate(c, [r for r in rows if r["gold"] == c]) for c in big]
    rest = [r for r in rows if r["gold"] not in big]
    by_origin.append(rate(f"{len({r['gold'] for r in rest})} others", rest))

    wrong = [r for r in rows if not r["correct"]]
    china = {
        "missed_china": sum(r["gold"] == "China" for r in wrong),
        "missed_china_auto": sum(r["gold"] == "China" and auto(r) for r in wrong),
        "said_china": sum(r["pred"] == "China" and r["gold"] != "China" for r in wrong),
        "said_china_auto": sum(r["pred"] == "China" and r["gold"] != "China" and auto(r) for r in wrong),
        "neither": sum(r["pred"] != "China" and r["gold"] != "China" for r in wrong),
    }

    return {
        "note": "Generated by eval/charts/build_trust_data.py from committed files. Do not edit by hand.",
        "source": RUN,
        "source_sha256": sha256(RUN),
        "scope_source": SCOPE,
        "bar": BAR,
        "calibrated_bar": cal["bar"],
        "calibration": cal["version"],
        "n": len(rows),
        "correct": sum(r["correct"] for r in rows),
        "auto_accepted": sum(auto(r) for r in rows),
        "misses": misses,
        "by_origin": by_origin,
        "china": china,
        "by_collection": [rate(c, [r for r in rows if labels[r["ruling"]]["collection"] == c]) for c in ("NY", "HQ")],
    }


def tally(xs):
    out = {}
    for x in xs:
        out[x] = out.get(x, 0) + 1
    return dict(sorted(out.items(), key=lambda kv: (-kv[1], kv[0])))


def stats():
    labels = jsonl(LABELS)
    with open(path(SPLITS)) as f:
        splits = json.load(f)
    st = [r for r in labels if r["regime"] == "substantial_transformation"]
    held = [r for r in st if r["primary_origin"]]
    origins = tally(r["primary_origin"] for r in held)
    by_id = {r["ruling"]: r for r in labels}

    def split(name):
        ids = splits[name]
        rs = [by_id[i] for i in ids]
        return {
            "n": len(ids),
            "first": min(r["date"] for r in rs),
            "last": max(r["date"] for r in rs),
            "collection": tally(r["collection"] for r in rs),
            "label_method": tally(r["method"] for r in rs),
            "origins_top": dict(list(tally(r["primary_origin"] for r in rs).items())[:8]),
        }

    return {
        "note": "Generated by eval/charts/build_trust_data.py from committed files. Do not edit by hand.",
        "labels": {
            "rulings": len(labels),
            "first": min(r["date"] for r in labels),
            "last": max(r["date"] for r in labels),
            "by_year": dict(sorted(tally(r["date"][:4] for r in labels).items())),
            "collection": tally(r["collection"] for r in labels),
            "regime": tally(r["regime"] for r in labels),
            "label_method": tally(r["method"] for r in labels),
        },
        "substantial_transformation": {
            "rulings": len(st),
            "with_held_origin": len(held),
            "collection": tally(r["collection"] for r in st),
            "distinct_origins": len(origins),
            "origins_top15": dict(list(origins.items())[:15]),
            "china_or_asean_share": round(
                sum(n for c, n in origins.items() if c in ASIA) / len(held), 4
            ),
        },
        "facts_files": len([f for f in os.listdir(path(FACTS)) if f.endswith(".txt")]),
        "splits": {name: split(name) for name in ("dev", "final", "pilot")},
    }


# China plus the ASEAN members, the countries the product is built around.
ASIA = {"China", "Vietnam", "Thailand", "Malaysia", "Indonesia", "Philippines", "Cambodia", "Singapore", "Laos", "Myanmar", "Brunei"}


def main():
    outs = {OUT: build(), STATS: stats()}
    stale = []
    for p, data in outs.items():
        text = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
        if CHECK:
            try:
                with open(path(p)) as f:
                    if f.read() != text:
                        stale.append(p)
            except FileNotFoundError:
                stale.append(p)
            continue
        with open(path(p), "w") as f:
            f.write(text)
        print("wrote", p)
    if CHECK:
        if stale:
            print("stale (re-run without --check):", ", ".join(stale))
            sys.exit(1)
        print("ok")


if __name__ == "__main__":
    main()
