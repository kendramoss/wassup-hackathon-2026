"""Write the four specialist datasets (dev and reserved test) and sources.json.

    python3 -I eval/challenges/specialists/build.py [--check]

Deterministic. --check fails if the committed files differ from regenerated bytes.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *
import textile, pharma, part102, japan

MODS = {"textile_specialist": textile, "pharma_specialist": pharma, "part102_specialist": part102, "japan_engine": japan}
FILES = {"textile_specialist": "textile", "pharma_specialist": "pharma", "part102_specialist": "part102", "japan_engine": "japan"}


def main():
    check = "--check" in sys.argv
    allc = {}
    for feat, mod in MODS.items():
        for split in ("dev", "test"):
            cases = mod.build(split)
            allc[(feat, split)] = cases
    # cross-split disjointness of normalised inputs, across every feature
    seen = {}
    for (feat, split), cases in allc.items():
        for c in cases:
            n = norm(c["input"]["facts"])
            assert n not in seen, "normalised input shared by %s and %s" % (seen[n], c["id"])
            seen[n] = c["id"]
    ids = [c["id"] for cs in allc.values() for c in cs]
    assert len(ids) == len(set(ids)), "duplicate id"
    for (feat, split), cases in allc.items():
        path = os.path.join(HERE, "%s-%s.jsonl" % (FILES[feat], split))
        tmp = path + ".new" if check else path
        write_jsonl(tmp, cases)
        if check:
            if open(tmp, "rb").read() != open(path, "rb").read():
                sys.exit("%s differs from regenerated bytes" % path)
            os.remove(tmp)
    print("datasets %s" % ("reproduce" if check else "written"))


if __name__ == "__main__":
    main()
