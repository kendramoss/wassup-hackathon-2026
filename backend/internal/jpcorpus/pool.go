package jpcorpus

import (
	"bytes"
	"compress/gzip"
	_ "embed"
	"encoding/json"
	"fmt"
	"io"
	"net/url"
	"sort"
	"time"

	"github.com/kendramoss/wassup-hackathon-2026/backend/internal/domain"
	"github.com/kendramoss/wassup-hackathon-2026/backend/internal/retrieval"
)

//go:embed data/precedents.json.gz
var embeddedPool []byte

type translatedPrecedent struct {
	Agreement string        `json:"agreement"`
	URL       string        `json:"url"`
	Ruling    domain.Ruling `json:"ruling"`
}

// Pool is a dated English precedent index, split by agreement. Its URLs
// refer to the original Japan Customs source pages.
type Pool struct {
	byID    map[string]translatedPrecedent
	indexes map[string]*retrieval.BM25
}

// NewPool indexes the specified corpus subset. Use only development IDs
// when tuning the engine.
func NewPool(c *Corpus, ids []string) (*Pool, error) {
	records, err := poolRecords(c, ids)
	if err != nil {
		return nil, err
	}
	return indexPool(records)
}

// EmbeddedPool loads Japan Customs' published rulings from the runtime
// snapshot generated by jpeval bundle.
func EmbeddedPool() (*Pool, error) {
	z, err := gzip.NewReader(bytes.NewReader(embeddedPool))
	if err != nil {
		return nil, fmt.Errorf("jpcorpus: open embedded snapshot: %w", err)
	}
	defer z.Close()
	var records []translatedPrecedent
	dec := json.NewDecoder(z)
	if err := dec.Decode(&records); err != nil {
		return nil, fmt.Errorf("jpcorpus: read embedded snapshot: %w", err)
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		return nil, fmt.Errorf("jpcorpus: embedded snapshot has trailing or unreadable data: %v", err)
	}
	return indexPool(records)
}

// WriteBundle encodes the runtime snapshot from the same translations we
// use in evaluation. It does not read labels, and it never calls a model.
func WriteBundle(w io.Writer, c *Corpus, ids []string) error {
	records, err := poolRecords(c, ids)
	if err != nil {
		return err
	}
	z := gzip.NewWriter(w)
	enc := json.NewEncoder(z)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(records); err != nil {
		_ = z.Close()
		return err
	}
	return z.Close()
}

func poolRecords(c *Corpus, ids []string) ([]translatedPrecedent, error) {
	ids = append([]string(nil), ids...)
	sort.Strings(ids)
	records := make([]translatedPrecedent, 0, len(ids))
	for _, id := range ids {
		r, _ := c.Ruling(id)
		p, err := c.Precedent(id)
		if err != nil {
			return nil, err
		}
		records = append(records, translatedPrecedent{r.Agreement, r.URL, p})
	}
	return records, nil
}

func indexPool(records []translatedPrecedent) (*Pool, error) {
	if len(records) == 0 {
		return nil, fmt.Errorf("jpcorpus: empty precedent pool")
	}
	p := &Pool{byID: make(map[string]translatedPrecedent, len(records)), indexes: map[string]*retrieval.BM25{}}
	groups := map[string][]domain.Ruling{}
	for _, record := range records {
		r := record.Ruling
		u, err := url.Parse(record.URL)
		if err != nil || u.Scheme != "https" || u.Host != "www.customs.go.jp" || u.User != nil {
			return nil, fmt.Errorf("jpcorpus: invalid source URL in ruling %s", r.ID)
		}
		if _, exists := p.byID[r.ID]; exists || r.ID == "" || r.Date.IsZero() || record.Agreement == "" || r.Facts == "" {
			return nil, fmt.Errorf("jpcorpus: invalid or duplicate ruling %q", r.ID)
		}
		p.byID[r.ID] = record
		groups[record.Agreement] = append(groups[record.Agreement], r)
	}
	for agreement, group := range groups {
		p.indexes[agreement] = retrieval.NewBM25(group, func(r domain.Ruling) string { return r.Facts })
	}
	return p, nil
}

// Get looks up a Japan precedent by its JP-prefixed ID, returning the
// English rendering and the source URL.
func (p *Pool) Get(id string) (domain.Ruling, string, bool) {
	record, ok := p.byID[id]
	return record.Ruling, record.URL, ok
}

// Top selects relevant precedents from the requested agreement and strictly
// before the calendar day of the case.
func (p *Pool) Top(c domain.Case, agreement, query string, k int) []domain.Ruling {
	idx := p.indexes[agreement]
	if idx == nil || k <= 0 {
		return nil
	}
	y, m, d := c.Date.Date()
	c.Date = time.Date(y, m, d, 0, 0, 0, 0, time.UTC)
	hits := idx.Top(query, k, retrieval.PrecedentFilter(c))
	out := make([]domain.Ruling, 0, len(hits))
	for _, hit := range hits {
		if hit.Score > 0 {
			out = append(out, hit.Ruling)
		}
	}
	return out
}
