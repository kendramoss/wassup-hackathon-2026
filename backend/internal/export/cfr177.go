package export

import (
	"fmt"
	"strings"

	"github.com/kendramoss/wassup-hackathon-2026/backend/internal/domain"
)

// FillIn starts every placeholder in the 19 CFR 177.2 letter: what the case
// does not know, for the requester or counsel to complete or delete.
const FillIn = "[FILL IN"

// CFR177 renders the draft as a ruling-request letter laid out on the
// contents 19 CFR 177.2 requires (parties, port, transaction, merchandise,
// question, position with authority, prior transactions, documents,
// confidentiality, signature), with CBP's eRulings checklist for origin
// requests: where each material and each production step comes from. It
// fills what the case knows and marks the rest [FILL IN: ...] (D66).
func CFR177(in Input) string {
	var b strings.Builder
	b.WriteString("> **Draft for review by a licensed customs broker or counsel.** " + domain.Disclaimer +
		" This draft was generated by Unde from the facts below; check every fact and citation before filing.\n\n")
	b.WriteString("> Laid out on 19 C.F.R. § 177.2. Every **[FILL IN: …]** is something Unde does not know: complete it or delete it before filing.\n\n")
	if in.BelowBar != nil {
		fmt.Fprintf(&b, "> **Below the confidence bar:** Unde's precedent check rated this change %.2f, under its %.2f bar. Treat the cited support as weaker and confirm with counsel.\n\n",
			in.BelowBar.Confidence, in.BelowBar.Bar)
	}
	name := in.ProductName
	if name == "" {
		name = "the subject merchandise"
	}
	rule := "substantial transformation (19 C.F.R. § 134.1(b))"
	if in.Textile {
		rule = "19 C.F.R. § 102.21"
	}

	b.WriteString("[FILL IN: date]\n\n")
	b.WriteString("Director, National Commodity Specialist Division  \nRegulations and Rulings, Office of International Trade  \nU.S. Customs and Border Protection  \n201 Varick Street, Suite 501  \nNew York, NY 10014\n\n")
	b.WriteString("(Or filed electronically through eRulings, https://erulings.cbp.gov.)\n\n")
	fmt.Fprintf(&b, "**RE: Request for a binding ruling under 19 C.F.R. Part 177 — country of origin of %s**\n\n", name)
	b.WriteString("Dear Director:\n\n")
	fmt.Fprintf(&b, "Pursuant to 19 C.F.R. §§ 177.1 and 177.2, [FILL IN: requester's legal name] respectfully requests a binding ruling on the country of origin of %s, determined under %s, for purposes of country of origin marking (19 U.S.C. § 1304; 19 C.F.R. Part 134) and the application of Section 301 duties. The request concerns prospective importations.\n\n", name, rule)

	b.WriteString("## 1. Interested parties\n\n")
	b.WriteString("- Requester: [FILL IN: legal name, address, email and telephone]. Interest in the question (19 C.F.R. § 177.1(c)): [FILL IN: importer, exporter or other interest].\n")
	b.WriteString("- Importer of record: [FILL IN: name, address and importer number, or \"the requester\"].\n")
	boughtIn := false
	if in.Product != nil && len(in.Product.Plants) > 0 {
		for _, pl := range in.Product.Plants {
			fmt.Fprintf(&b, "- Manufacturer, %s (%s): [FILL IN: legal name, address and manufacturer identification (MID) code].\n", pl.Name, pl.Country)
		}
		for _, c := range in.Product.Components {
			boughtIn = boughtIn || c.Plant == ""
		}
	} else {
		b.WriteString("- Manufacturer(s): [FILL IN: legal name, address and manufacturer identification (MID) code of each].\n")
	}
	if boughtIn {
		b.WriteString("- Suppliers of bought-in components: [FILL IN: names and addresses, if known].\n")
	}
	b.WriteString("- Agent filing for the requester: [FILL IN: name and address, or delete].\n\n")

	b.WriteString("## 2. Port of entry\n\n[FILL IN: the port or ports where the merchandise will be entered, if known].\n\n")

	b.WriteString("## 3. The transaction\n\n")
	fmt.Fprintf(&b, "Prospective importation of %s, produced as described in sections 4 and 5, exported from [FILL IN: country of exportation].", name)
	switch {
	case in.CurrentRuled != "" && in.PlanSummary != "":
		fmt.Fprintf(&b, " CBP has ruled on the current production setup: origin %s. This request concerns a proposed change to that setup: %s.", in.CurrentRuled, lowerFirst(in.PlanSummary))
	case in.CurrentRuled != "":
		fmt.Fprintf(&b, " CBP has ruled on this production setup: origin %s.", in.CurrentRuled)
	case in.PlanSummary != "":
		fmt.Fprintf(&b, " This request concerns a proposed production setup: %s.", lowerFirst(in.PlanSummary))
	}
	b.WriteString(" [FILL IN: expected date of the first shipment].\n\n")

	b.WriteString("## 4. The merchandise\n\n")
	if in.ProductName != "" {
		fmt.Fprintf(&b, "- Name and model: %s.\n", in.ProductName)
	} else {
		b.WriteString("- Name and model: [FILL IN: commercial name and model number].\n")
	}
	if in.Product != nil && strings.TrimSpace(in.Product.Description) != "" {
		fmt.Fprintf(&b, "- Description: %s\n", strings.TrimSpace(in.Product.Description))
	} else {
		b.WriteString("- Description: [FILL IN: what the article is, how it works and its chief use in the United States].\n")
	}
	if in.Product != nil && in.Product.HTS != "" {
		fmt.Fprintf(&b, "- HTSUS subheading, for reference (classification is not requested): %s.\n", in.Product.HTS)
	} else {
		b.WriteString("- HTSUS subheading, for reference (classification is not requested): [FILL IN].\n")
	}
	b.WriteString("- Proposed origin marking of the article and its container: [FILL IN: wording, method and location; attach illustrations].\n\n")

	b.WriteString("## 5. Materials, countries and processing\n\n")
	if in.Product != nil && len(in.Product.Components) > 0 {
		b.WriteString("Components and where each is made:\n\n")
		for _, c := range in.Product.Components {
			where := "bought in"
			if pl, ok := in.Product.PlantByID(c.Plant); ok {
				where = pl.Name
			}
			fmt.Fprintf(&b, "- %s: %s (%s).\n", c.Name, c.MadeIn, where)
		}
		b.WriteString("\n")
		if len(in.Product.Operations) > 0 {
			b.WriteString("Production steps and where each takes place:\n\n")
			for _, o := range in.Product.Operations {
				where := "[FILL IN: plant and country]"
				if pl, ok := in.Product.PlantByID(o.Plant); ok {
					where = pl.Name + ", " + pl.Country
				}
				fmt.Fprintf(&b, "- %s: %s.\n", o.Name, where)
			}
			b.WriteString("\n")
		}
	}
	b.WriteString("Production as described:\n\n")
	b.WriteString(strings.TrimSpace(in.Facts) + "\n\n")
	b.WriteString("[FILL IN: cost or share of value of each component, and the time and skill each step takes, if available].\n\n")

	b.WriteString("## 6. Question presented\n\n")
	fmt.Fprintf(&b, "What is the country of origin of %s, produced as described above, under %s, for purposes of country of origin marking and Section 301 duties?\n\n", name, rule)

	b.WriteString("## 7. Requester's position and supporting authority\n\n")
	if in.Requested != "" {
		fmt.Fprintf(&b, "The requester submits that the merchandise is a product of %s", in.Requested)
	} else {
		b.WriteString("The requester submits that the merchandise is a product of [FILL IN: country]")
	}
	if len(in.Prediction.KeyFactors) > 0 {
		fmt.Fprintf(&b, ", based on these key factors: %s", listPhrase(in.Prediction.KeyFactors))
	}
	b.WriteString(". [FILL IN: the legal basis, with counsel].\n\nEarlier CBP rulings relied on (19 C.F.R. § 177.2(b)(6)):\n\n")
	b.WriteString(strings.Join(citations(in), "\n") + "\n\n")

	b.WriteString("## 8. Prior or current consideration\n\n")
	b.WriteString("To the knowledge of the requester, the same transaction, or one identical to it, has not been considered and is not being considered by any CBP office, and the issues involved have not been considered by and are not pending before the U.S. Court of International Trade, the U.S. Court of Appeals for the Federal Circuit or any court of appeal therefrom. [FILL IN: confirm, or name the office or court, the date and the reference].\n\n")
	if in.CurrentRuled != "" {
		fmt.Fprintf(&b, "CBP's ruling on the current setup, origin %s, is described in section 3. [FILL IN: whether it was issued to the requester, and how this transaction differs from it].\n\n", in.CurrentRuled)
	}
	b.WriteString("Advice sought from a CBP office on this merchandise: [FILL IN: none, or from whom and the advice given].\n\n")
	b.WriteString("This transaction [FILL IN: is / is not] one of a series of similar and related transactions.\n\n")

	b.WriteString("## 9. Documents and samples\n\n")
	b.WriteString("- Exhibit A: bill of materials with the country of origin of each component.\n")
	b.WriteString("- Exhibit B: process flow of each production step, with where it takes place.\n")
	b.WriteString("- Exhibit C: photographs or drawings of the article (19 C.F.R. § 177.2(b)(3)).\n")
	b.WriteString("- Invoices, contracts or agreements the question relates to (19 C.F.R. § 177.2(b)(4)): [FILL IN: list, or none].\n")
	b.WriteString("- Sample: [FILL IN: sent separately, or not sent; if it should be returned, how].\n\n")

	b.WriteString("## 10. Confidential treatment\n\n")
	b.WriteString("[FILL IN: keep one of the two statements and delete the other.]\n\n")
	b.WriteString("- The requester does not request confidential treatment of any information in this request.\n")
	b.WriteString("- Under 19 C.F.R. § 177.2(b)(7), the requester asks that the information in brackets [[ ]] in this letter and its exhibits, namely [FILL IN: e.g. supplier names, costs], be withheld from disclosure as confidential commercial information, because its disclosure would cause substantial harm to the requester's competitive position: [FILL IN: reasons]. If CBP denies this, the requester may withdraw the request within 10 working days of notification (19 C.F.R. § 177.8(a)(3)).\n\n")

	b.WriteString("## 11. Declaration and signature\n\n")
	b.WriteString("I am authorized to make this request on behalf of the requester (19 C.F.R. §§ 177.1(c), 177.2(c)). To the best of my knowledge and belief, the facts stated in this request and its exhibits are accurate and complete. Please address the ruling letter to [FILL IN: the requester or its agent].\n\n")
	// One line each, as a letter is signed; "  " ends a Markdown line (18 Oct).
	b.WriteString("Sincerely,\n\n[FILL IN: signature]  \n[FILL IN: name of signer]  \n[FILL IN: title]  \n[FILL IN: company]  \n[FILL IN: address]  \n[FILL IN: email and telephone]\n")
	return b.String()
}
