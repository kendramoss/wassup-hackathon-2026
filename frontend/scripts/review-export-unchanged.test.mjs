test("the download is the raw letter with the requester's fields filled in, byte for byte, and none of the new copy", async () => {
  const env = setup();
  const app = await mount();
  // One event at a time, re-rendering between them, as a browser does.
  const set = (label, v) => {
    app.find((e) => e.type === "input" && e.props.id?.endsWith(label))[0].props.onChange({ target: { value: v } });
    app.refresh();
  };
  set("[REQUESTER NAME]", "Acme Ltd");
  set("[NAME]", "Jane Doe");
  set("[TITLE]", "Compliance lead");
  set("[COMPANY]", "Acme Ltd");
  app.find((e) => e.type === "textarea")[0].props.onChange({ target: { value: "1 Main St" } });
  app.refresh();
  set("[CONTACT]", "jane@example.com");
  app.refresh();
  await app.btn("Download Markdown").props.onClick();
  await app.flush();
  assert.equal(env.blobs.length, 1);
  const expected = "# Ruling request\n\nTo CBP, from Acme Ltd.\n\nThe motor is made in Vietnam.\n\nSigned Jane Doe, Compliance lead, Acme Ltd\n1 Main St\njane@example.com\n";
  const got = Buffer.from(await env.blobs[0].arrayBuffer());
  assert.equal(got.toString("utf8"), expected, "download bytes are exactly the letter");
  assert.equal(env.blobs[0].type, "text/markdown");
  for (const s of [...NEW_COPY, ...SERVER_NOTES]) assert.ok(!got.toString("utf8").includes(s.slice(0, 40)), `not in the download: ${s.slice(0, 40)}`);
});

