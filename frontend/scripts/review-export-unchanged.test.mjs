test("on screen: the letter article holds the letter and nothing else; every note is a sibling before it, not inside it", async () => {
  setup();
  const app = await mount();
  const article = letterEl(app);
  assert.ok(article, "the letter article is on screen");
  const inside = new Set();
  const collect = (n) => {
    if (n && typeof n === "object") {
      if (Array.isArray(n)) n.forEach(collect);
      else {
        inside.add(n);
        collect(n.props?.children);
      }
    }
  };
  collect(article.props.children);
  const notes = renderedNotes(app);
  assert.ok(notes.some((n) => n.name === "ReviewNotes"), "the server notes are rendered");
  for (const n of notes) assert.ok(!inside.has(n.el), `${n.name} is not inside the letter`);
  // Same parent, notes first, then the letter.
  const frag = app.find((e) => Array.isArray(e.props?.children) && e.props.children.includes(article))[0];
  const kids = frag.props.children;
  const at = (name) => kids.findIndex((k) => k?.type?.name === name);
  assert.ok(at("ReviewNotes") >= 0 && at("ReviewNotes") < kids.indexOf(article), "server notes sit before the letter");
  // The rendered server notes carry the words as sent.
  const rn = notes.find((n) => n.name === "ReviewNotes");
  for (const m of SERVER_NOTES) assert.ok(rn.text.includes(m.slice(0, 60)));
  // The letter's own text: the raw preview, no note words.
  const letterText = JSON.stringify(article.props.children);
  for (const s of [...NEW_COPY, ...SERVER_NOTES]) assert.ok(!letterText.includes(s.slice(0, 40)));
});

test("every note is hidden when printing: it has the existing no-print class, and that class is hidden in the print CSS", async () => {
  setup();
  const app = await mount();
  const notes = renderedNotes(app);
  assert.ok(notes.length > 0);
  for (const n of notes) assert.match(n.markup, /class="[^"]*\bno-print\b/, n.name);
  const css = await readFile(new URL("../src/app/globals.css", import.meta.url), "utf8");
  assert.match(css, /@media print[\s\S]*\.no-print\s*\{\s*display:\s*none\s*!important/);
  const article = letterEl(app);
  assert.doesNotMatch(String(article.props.className), /no-print/, "the letter itself is what prints");
});

