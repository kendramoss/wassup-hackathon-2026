function setup({ readOnly = false } = {}) {
  const calls = [];
  const bodies = { markdown: SHORT, cfr177: LONG };
  globalThis.fetch = async (url, init = {}) => {
    const u = String(url);
    const m = init.method ?? "GET";
    const body = typeof init.body === "string" ? JSON.parse(init.body) : undefined;
    calls.push({ m, u, body });
    if (u.endsWith("/export") && m === "POST") return json({ content: bodies[body.format ?? "markdown"], notes: SERVER_NOTES, format: body.format ?? "markdown" });
    if (/\/cases\/c1$/.test(u) && m === "GET")
      return json({ id: "c1", facts: "f", step: "export", date: "2026-01-01", display_name: "Widget", prediction: { origin_country: "China" }, product: { name: "W", plants: [], components: [], operations: [] }, can_write: !readOnly });
    if (u.includes("/demos")) return json({ demos: [] });
    return json({});
  };
  const blobs = [];
  let printed = 0;
  globalThis.window.print = () => printed++;
  globalThis.URL.createObjectURL = (b) => (blobs.push(b), "blob:test");
  globalThis.URL.revokeObjectURL = () => {};
  globalThis.document.createElement = () => ({ click() {}, set href(v) {}, set download(v) { this.name = v; } });
  return { calls, blobs, printed: () => printed };
}
function mountScreen() {
  const app = {};
  let sched = false;
  const schedule = () => {
    if (sched) return;
    sched = true;
    queueMicrotask(() => {
      sched = false;
      app.refresh();
    });
  };
  const shellEl = DraftStep();
  const shell = instance(shellEl.type, schedule);
  const screen = instance(null, schedule);
  app.refresh = () => {
    for (let n = 0; n < 30 && (shell.dirty || screen.dirty || !shell.tree); n++) {
      shell.render(shellEl.props);
      const sEl = findAll(shell.tree, byName("Draft"))[0];
      if (!sEl) continue;
      screen.Component = sEl.type;
      screen.render(sEl.props);
    }
  };
  app.flush = async () => {
    for (let n = 0; n < 8; n++) {
      await tick();
      app.refresh();
    }
  };
  app.find = (pred) => findAll(screen.tree, pred);
  app.btn = (label) => app.find((e) => byName("Button")(e) && JSON.stringify(e.props.children).includes(label))[0];
  app.tree = () => screen.tree;
  return app;
}
async function mount() {
  const app = mountScreen();
  app.refresh();
  await app.flush();
  return app;
}
const letterEl = (app) => app.find((e) => e.type === "article" && /\bletter\b/.test(e.props.className ?? ""))[0];
// Rendered text of every note element on the screen (the unexpanded tree holds
