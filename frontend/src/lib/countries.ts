// Flag codes for a country name. "Indonesia/Malaysia" gives both; an unknown
// or empty name gives none.
export function flagCodes(name: string | null | undefined): string[] {
  if (!name) return [];
  return name
    .split("/")
    .map((part) => countryCodes[part.trim()])
    .filter((c): c is string => Boolean(c));
}
