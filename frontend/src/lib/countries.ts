const byLower: Record<string, string> = Object.fromEntries([
  ...allCountries.map(([n, c]) => [n.toLowerCase(), c]),
  ...Object.entries(countryCodes).map(([n, c]) => [n.toLowerCase(), c]),
]);

// Flag codes for a country name, matched case-insensitively ("Bosnia And
// Herzegovina", as the backend title-cases it, still has a flag).
export function flagCodes(name: string | null | undefined): string[] {
  if (!name) return [];
  return name
    .split("/")
    .map((part) => byLower[part.trim().toLowerCase()])
    .filter((c): c is string => Boolean(c));
}
